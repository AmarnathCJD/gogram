type Generator struct {
	schema *internalSchema
	outdir string

	PackageName        string
	PackageHeader      string
	existingDocs       map[string]string
	existingFieldDocs  map[string]map[string]string
	existingMethodDocs map[string]string
}

func NewGenerator(tlschema *tlparser.Schema, licenseHeader, outdir string) (*Generator, error) {
	internalSchema, err := createInternalSchema(tlschema)
	if err != nil {
		return nil, fmt.Errorf("analyzing schema: %w", err)
	}

	return &Generator{
		schema:        internalSchema,
		outdir:        outdir,
		PackageName:   "telegram",
		PackageHeader: licenseHeader + "\nCode generated by tlgen; DO NOT EDIT.",
	}, nil
}

func (g *Generator) Generate(d bool) error {
	log.Println("INFO: Starting code generation process")
	if !d {
		g.loadExistingDocumentation()
	}

	log.Println("INFO: Generating enum definitions...")
	err := g.generateFile(g.generateEnumDefinitions, filepath.Join(g.outdir, "enums_gen.go"), d)
	if err != nil {
		log.Printf("ERROR: Failed to generate enums: %v\n", err)
		return fmt.Errorf("generate enums: %w", err)
	}

	log.Println("INFO: Generating struct types...")
	err = g.generateFile(g.generateSpecificStructs, filepath.Join(g.outdir, "types_gen.go"), d)
	if err != nil {
		log.Printf("ERROR: Failed to generate types: %v\n", err)
		return fmt.Errorf("generate types: %w", err)
	}

	log.Println("INFO: Generating interfaces...")
	err = g.generateFile(g.generateInterfaces, filepath.Join(g.outdir, "interfaces_gen.go"), d)
	if err != nil {
		log.Printf("ERROR: Failed to generate interfaces: %v\n", err)
		return fmt.Errorf("generate interfaces: %w", err)
	}

	log.Println("INFO: Generating methods...")
	err = g.generateFile(g.generateMethods, filepath.Join(g.outdir, "methods_gen.go"), d)
	if err != nil {
		log.Printf("ERROR: Failed to generate methods: %v\n", err)
		return fmt.Errorf("generate methods: %w", err)
	}

	log.Println("INFO: Generating initialization code...")
	err = g.generateFile(g.generateInit, filepath.Join(g.outdir, "init_gen.go"), d)
	if err != nil {
		log.Printf("ERROR: Failed to generate init: %v\n", err)
		return fmt.Errorf("generate init: %w", err)
	}

	log.Println("INFO: Code generation completed successfully")
	return nil
}

// Local schema regeneration retains documentation already fetched by --doc.
// It must not require another network crawl or discard public API comments.
func (g *Generator) loadExistingDocumentation() {
	g.existingDocs = make(map[string]string)
	g.existingFieldDocs = make(map[string]map[string]string)
	g.existingMethodDocs = make(map[string]string)
	for _, name := range []string{"types_gen.go", "interfaces_gen.go", "methods_gen.go"} {
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(g.outdir, name), nil, parser.ParseComments)
		if err != nil {
			continue
		}
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Doc != nil {
					g.existingMethodDocs[d.Name.Name] = d.Doc.Text()
				}
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					t, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					doc := t.Doc
					if doc == nil {
						doc = d.Doc
					}
					if doc != nil {
						g.existingDocs[t.Name.Name] = doc.Text()
					}
					st, ok := t.Type.(*ast.StructType)
					if !ok {
						continue
					}
					fields := make(map[string]string)
					for _, field := range st.Fields.List {
						if field.Comment != nil {
							for _, id := range field.Names {
								fields[id.Name] = field.Comment.Text()
							}
						}
					}
					g.existingFieldDocs[t.Name.Name] = fields
				}
			}
		}
	}
}

func (*Generator) generateFile(f func(file *jen.File, d bool), filename string, genDocs bool) error {
	log.Printf("INFO: Generating file: %s\n", filename)
	file := jen.NewFile("telegram")
	file.HeaderComment("Code generated by TLParser; DO NOT EDIT. (c) @amarnathcjd")
	f(file, genDocs)

	buf := bytes.NewBuffer([]byte{})
	if err := file.Render(buf); err != nil {
		log.Printf("ERROR: Failed to render file %s: %v\n", filename, err)
		dumpPath := filename + ".broken"
		if writeErr := os.WriteFile(dumpPath, buf.Bytes(), 0600); writeErr == nil {
			log.Printf("ERROR: Wrote partial output to %s for inspection\n", dumpPath)
			return fmt.Errorf("render %s: %w (partial output saved to %s)", filename, err, dumpPath)
		}
		return fmt.Errorf("render %s: %w", filename, err)
	}

	if err := os.WriteFile(filename, buf.Bytes(), 0600); err != nil {
		log.Printf("ERROR: Failed to write file %s: %v\n", filename, err)
		return err
	}

	log.Printf("INFO: Successfully wrote file: %s\n", filename)
	return nil
}
